/**
 * Medical Assessment Reports routes for Cloudflare Workers & D1.
 * Uses jsPDF to generate downloadable PDF reports at the edge.
 */
import { Hono } from 'hono';
import { jsPDF } from 'jspdf';
import { authMiddleware } from '../auth.js';

const reports = new Hono();

function generateId(prefix = 'rep') {
  return `${prefix}_${Date.now().toString(36)}_${Math.random().toString(36).substring(2, 9)}`;
}

function buildPdfBytes(assessment, prediction, user) {
  const doc = new jsPDF();

  // Header
  doc.setFillColor(37, 99, 235); // Blue
  doc.rect(0, 0, 210, 24, 'F');
  doc.setTextColor(255, 255, 255);
  doc.setFontSize(16);
  doc.setFont('helvetica', 'bold');
  doc.text('AI Medical Symptom Assistant Report', 14, 16);

  // Subheader
  doc.setTextColor(100, 116, 139);
  doc.setFontSize(9);
  doc.setFont('helvetica', 'normal');
  doc.text(`Generated: ${new Date().toLocaleString()} | Cloudflare Edge Engine`, 14, 32);

  // Patient Info Box
  doc.setFillColor(248, 250, 252);
  doc.rect(14, 36, 182, 28, 'F');
  doc.setDrawColor(226, 232, 240);
  doc.rect(14, 36, 182, 28, 'S');

  doc.setTextColor(30, 41, 59);
  doc.setFontSize(10);
  doc.setFont('helvetica', 'bold');
  doc.text(`Patient: ${user.full_name || user.name || 'Patient'}`, 18, 44);
  doc.setFont('helvetica', 'normal');
  doc.text(`Email: ${user.email}`, 18, 51);
  doc.text(`Age: ${user.age || 'N/A'} | Gender: ${user.gender || 'N/A'}`, 18, 58);

  doc.text(`Duration: ${assessment.duration || '1-3 days'}`, 120, 44);
  doc.text(`Severity: ${assessment.severity || 'Moderate'}`, 120, 51);
  doc.text(`Input: ${assessment.input_method || 'text'}`, 120, 58);

  // Emergency Banner if flagged
  let y = 72;
  if (assessment.is_emergency === 1) {
    doc.setFillColor(254, 242, 242);
    doc.rect(14, y, 182, 14, 'F');
    doc.setDrawColor(239, 68, 68);
    doc.rect(14, y, 182, 14, 'S');
    doc.setTextColor(220, 38, 38);
    doc.setFont('helvetica', 'bold');
    doc.setFontSize(10);
    doc.text('! EMERGENCY WARNING: Urgent medical evaluation is recommended.', 18, y + 9);
    y += 20;
  }

  // Reported Symptoms
  doc.setTextColor(15, 23, 42);
  doc.setFontSize(12);
  doc.setFont('helvetica', 'bold');
  doc.text('Reported Symptoms:', 14, y);
  y += 7;

  let symptomsList = [];
  try { symptomsList = JSON.parse(assessment.symptoms); } catch (e) { symptomsList = []; }
  doc.setFontSize(10);
  doc.setFont('helvetica', 'normal');
  doc.setTextColor(51, 65, 85);
  doc.text(symptomsList.length > 0 ? symptomsList.join(', ') : (assessment.raw_symptoms_text || 'None listed'), 14, y);
  y += 14;

  // Predictions Section
  doc.setFontSize(12);
  doc.setFont('helvetica', 'bold');
  doc.setTextColor(15, 23, 42);
  doc.text('Possible Conditions (ML Prediction):', 14, y);
  y += 8;

  let top3 = [];
  try { top3 = JSON.parse(prediction?.top_3_conditions || '[]'); } catch (e) { top3 = []; }

  for (let i = 0; i < top3.length; i++) {
    const p = top3[i];
    doc.setFontSize(10);
    doc.setFont('helvetica', 'bold');
    doc.setTextColor(37, 99, 235);
    doc.text(`#${i + 1} ${p.disease} (${p.probability}%)`, 14, y);
    y += 5;

    doc.setFont('helvetica', 'normal');
    doc.setTextColor(71, 85, 105);
    if (p.description) {
      doc.text(p.description, 14, y, { maxWidth: 180 });
      y += 6;
    }
    if (p.advice) {
      doc.text(`Advice: ${p.advice}`, 14, y, { maxWidth: 180 });
      y += 8;
    }
    y += 2;
  }

  // Footer Disclaimer
  doc.setFontSize(8);
  doc.setTextColor(148, 163, 184);
  doc.setFont('helvetica', 'italic');
  doc.text(
    'Disclaimer: This report was automatically generated by an AI assistant on Cloudflare Workers for educational purposes only. It is not an official medical diagnosis. Please consult a licensed physician.',
    14,
    280,
    { maxWidth: 182 }
  );

  return doc.output('arraybuffer');
}

// POST /api/reports
reports.post('/', authMiddleware, async (c) => {
  const user = c.get('user');
  const body = await c.req.json().catch(() => null);

  if (!body || !body.assessment_id) {
    return c.json({ detail: 'Assessment ID is required.' }, 400);
  }

  const db = c.env.DB;

  const assessment = await db.prepare('SELECT * FROM assessments WHERE id = ? AND user_id = ?').bind(body.assessment_id, user.id).first();
  if (!assessment) {
    return c.json({ detail: 'Assessment record not found.' }, 404);
  }

  const pred = await db.prepare('SELECT * FROM predictions WHERE assessment_id = ?').bind(assessment.id).first();

  const reportId = generateId('rep');
  const filename = `report_${assessment.id}.pdf`;
  const now = new Date().toISOString();

  // Check if report already exists for this assessment
  const existing = await db.prepare('SELECT id FROM reports WHERE assessment_id = ? AND user_id = ?').bind(assessment.id, user.id).first();
  const finalReportId = existing ? existing.id : reportId;

  if (!existing) {
    await db.prepare('INSERT INTO reports (id, user_id, assessment_id, filename, file_path, created_at) VALUES (?, ?, ?, ?, ?, ?)').bind(
      finalReportId,
      user.id,
      assessment.id,
      filename,
      `/reports/${filename}`,
      now
    ).run();
  }

  return c.json({
    report_id: finalReportId,
    assessment_id: assessment.id,
    filename: filename,
    download_url: `/api/reports/${finalReportId}/pdf`,
    message: 'Report generated successfully.'
  });
});

// GET /api/reports/:id/pdf
reports.get('/:id/pdf', authMiddleware, async (c) => {
  const user = c.get('user');
  const id = c.req.param('id');
  const db = c.env.DB;

  const report = await db.prepare('SELECT * FROM reports WHERE id = ?').bind(id).first();
  if (!report) {
    return c.json({ detail: 'Report not found.' }, 404);
  }

  // Data isolation check: User must own report unless admin
  if (report.user_id !== user.id && user.role !== 'admin') {
    return c.json({ detail: 'Access denied. You can only access your own health reports.' }, 403);
  }

  const assessment = await db.prepare('SELECT * FROM assessments WHERE id = ?').bind(report.assessment_id).first();
  const prediction = await db.prepare('SELECT * FROM predictions WHERE assessment_id = ?').bind(report.assessment_id).first();

  if (!assessment) {
    return c.json({ detail: 'Assessment record not found.' }, 404);
  }

  const pdfBytes = buildPdfBytes(assessment, prediction, user);

  return new Response(pdfBytes, {
    headers: {
      'Content-Type': 'application/pdf',
      'Content-Disposition': `attachment; filename="${report.filename || 'medical_report.pdf'}"`
    }
  });
});

export default reports;
